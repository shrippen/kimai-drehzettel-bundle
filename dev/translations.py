# "drehzettel.mail.sent" -> "dz.mail.sent": stable when rows are added or moved.
def unit_id(key):
    return "dz." + key.removeprefix("drehzettel.")


def unit(key, source, target, lang):
    text = source if lang == "en" else target
    return (f'      <trans-unit id="{unit_id(key)}" resname="{key}">\n'
            f'        <source>{escape(key)}</source>\n'
            f'        <target>{escape(text)}</target>\n'
            f'      </trans-unit>\n')


def write(lang):
    body = "".join(unit(k, en, de, lang) for k, en, de in ROWS)
    xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
           '<xliff xmlns="urn:oasis:names:tc:xliff:document:1.2" version="1.2">\n'
           f'  <file source-language="en" target-language="{lang}" datatype="plaintext" original="DrehzettelBundle">\n'
           f'    <body>\n{body}    </body>\n  </file>\n</xliff>\n')
    (OUT / f"messages.{lang}.xlf").write_text(xml, encoding="utf-8")


